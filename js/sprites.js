  function size(name) {
    const sprite = sprites[name];
    return sprite ? { w: sprite.w, h: sprite.h, frames: sprite.frames.length } : null;
  }

  function draw(ctx, name, frame, x, y, scale, flip) {
    const sprite = sprites[name];
    if (!sprite || !ctx || !Number.isFinite(x) || !Number.isFinite(y)) return false;
    if (scale === undefined) scale = 1;
    if (!Number.isFinite(scale) || scale <= 0) return false;
    scale = Math.max(1, Math.round(scale));
    frame = Number.isFinite(frame) ? Math.floor(frame) : 0;
    frame = ((frame % sprite.frames.length) + sprite.frames.length) % sprite.frames.length;
    const key = name + ':' + frame;
    let tile = cache.get(key);
    if (!tile) {
      tile = document.createElement('canvas');
      tile.width = sprite.w; tile.height = sprite.h;
      const ink = tile.getContext('2d');
      ink.imageSmoothingEnabled = false;
      sprite.frames[frame].forEach(function (row, py) {
        for (let px = 0; px < row.length; px++) {
          if (row[px] === '.') continue;
          ink.fillStyle = sprite.palette[row[px]];
          ink.fillRect(px, py, 1, 1);
        }
      });
      cache.set(key, tile);
    }
    const w = sprite.w * scale, h = sprite.h * scale;
    x = Math.round(x); y = Math.round(y);
    ctx.save();
    ctx.imageSmoothingEnabled = false;
    if (flip) {
      ctx.translate(x + w, y);
      ctx.scale(-1, 1);
      ctx.drawImage(tile, 0, 0, w, h);
    } else ctx.drawImage(tile, x, y, w, h);
    ctx.restore();
    return true;
  }

